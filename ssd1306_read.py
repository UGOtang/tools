max_start = max(0, total_lines - LINES_PER_PAGE)
current_line = 0  # 当前显示的第一行索引
show_page_safe(current_line)

print("按键：K1上滚 K2下滚 K3(#)短按调亮/长按翻页 K4(*)短按调暗/长按回开头")
print("行：{}/{} 亮度：{}".format(current_line, max_start, BRIGHT_LEVELS[bright_idx]))

while True:
    key = read_key()
    if key is None:
        time.sleep_ms(10)
        continue
    name, dur = key
    is_long = dur >= LONG_ACTION_MS

    need_redraw = False  # 内容没变就不重绘，避免无谓闪屏
    if name == 'up':
        if current_line > 0:
            current_line -= 1
            need_redraw = True
        else:
            print("已在顶部")
    elif name == 'down':
        if current_line < max_start:
            current_line += 1
            need_redraw = True
        else:
            print("已在底部")
    elif name == 'hash':
        # K3 '#'：短按调亮（灰点密度会变，需重绘一次），长按翻页
        if is_long:
            if current_line + LINES_PER_PAGE <= max_start:
                current_line += LINES_PER_PAGE
                need_redraw = True
            elif current_line != max_start:
                current_line = max_start
                need_redraw = True
            else:
                print("已在底部")
        elif bright_idx == len(BRIGHT_LEVELS) - 1:
            print("已最亮")
        else:
            set_brightness(bright_idx + 1)
            need_redraw = True
    elif name == 'star':
        # K4 '*'：短按调暗（灰点密度会变，需重绘一次），长按回开头
        if is_long:
            if current_line != 0:
                current_line = 0
                need_redraw = True
        elif bright_idx == 0:
            print("已最暗")
        else:
            set_brightness(bright_idx - 1)
            need_redraw = True

    if need_redraw:
        show_page_safe(current_line)
        print("行：{}/{}".format(current_line, max_start))
    time.sleep_ms(20)

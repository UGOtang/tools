# ========== 中文显示函数（柔和版） ==========
def _lit(px, py):
    """该像素是否点亮：棋盘灰点留1/2（同 1 copy.py；1/4太虚像乱码，已去掉）"""
    if not DITHER:
        return True
    return ((px + py) & 1) == 1

def draw_mixed(s, x0, y0):
    """混排一行：中文16x16查字库，英文用自带8x8居中，全部做灰点柔光"""
    x = x0
    for ch in s:
        if ord(ch) < 128:
            if x + 8 > OLED_WIDTH:
                break
            oled.text(ch, x, y0 + 4, 1)
            if DITHER:
                for dy in range(8):
                    for dx in range(8):
                        px, py = x + dx, y0 + 4 + dy
                        if 0 <= px < OLED_WIDTH and 0 <= py < OLED_HEIGHT:
                            if not _lit(px, py) and oled.framebuf.pixel(px, py):
                                oled.framebuf.pixel(px, py, 0)
            x += 8
        else:
            if x + 16 > OLED_WIDTH:
                break
            bmp = CN_FONT.get(ch)
            if bmp:
                for yy in range(16):
                    b0 = bmp[yy * 2]
                    b1 = bmp[yy * 2 + 1]
                    for xx in range(16):
                        byte = b0 if xx < 8 else b1
                        if byte & (1 << (7 - (xx % 8))):
                            px, py = x + xx, y0 + yy
                            if 0 <= px < OLED_WIDTH and 0 <= py < OLED_HEIGHT:
                                if not _lit(px, py):
                                    continue
                                oled.framebuf.pixel(px, py, 1)
            else:
                oled.framebuf.rect(x, y0, 16, 16, 1)
            x += 16

def show_page(start_line):
    """从 start_line 开始显示一屏中文"""
    oled.fill(0)
    for i in range(LINES_PER_PAGE):
        idx = start_line + i
        if idx >= total_lines:
            break
        draw_mixed(lines[idx], 0, i * 16)
    oled.framebuf.hline(0, 54, OLED_WIDTH, 1)
    for px in range(OLED_WIDTH):
        if not _lit(px, 54):
            oled.framebuf.pixel(px, 54, 0)
    if total_lines > LINES_PER_PAGE:
        bar_w = int((start_line / (total_lines - LINES_PER_PAGE)) * (OLED_WIDTH - 2))
        oled.framebuf.fill_rect(1, 57, max(2, bar_w), 4, 1)
        for yy in (57, 58, 59, 60):
            for xx in range(1, 1 + max(2, bar_w)):
                if not _lit(xx, yy):
                    oled.framebuf.pixel(xx, yy, 0)
    oled.show()

# ========== 按键检测（防抖 + 短/长按 + 防卡死） ==========
_ignore_until_release = set()

def read_key():
    """有按键释放后返回 (键名, 按住时长ms)，无按键返回 None。
    超时仍未释放也返回一次长按，并在释放前不再触发，防卡死、防连发。"""
    for name, pin in keys.items():
        if name in _ignore_until_release:
            if pin.value() == 1:
                _ignore_until_release.discard(name)
            continue
        if pin.value() == 0:   # 按下（低电平有效）
            t0 = time.ticks_ms()
            time.sleep_ms(20)
            if pin.value() == 0:
                while pin.value() == 0:
                    if time.ticks_diff(time.ticks_ms(), t0) > LONG_PRESS_MS:
                        _ignore_until_release.add(name)
                        break
                    time.sleep_ms(10)
                return (name, time.ticks_diff(time.ticks_ms(), t0))
    return None

def show_page_safe(start_line):
    """show_page 加 I2C 异常保护：失败则保留上一屏，不闪黑"""
    try:
        show_page(start_line)
    except OSError:
        print("warn: oled show failed")

def set_brightness(idx):
    """设亮度档位并立即生效（只动 contrast；由调用方重绘确认）"""
    global bright_idx
    idx = max(0, min(len(BRIGHT_LEVELS) - 1, idx))
    if idx == bright_idx:
        return
    bright_idx = idx
    apply_brightness()
    print("亮度：", BRIGHT_LEVELS[bright_idx])


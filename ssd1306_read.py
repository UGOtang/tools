def wrap_cn(text, max_px=128):
    """按像素宽度换行：汉字16px，ASCII 8px，128px一行约8个汉字"""
    clines = []
    cur = ""
    w = 0
    for ch in text:
        cw = 8 if ord(ch) < 128 else 16
        if w + cw > max_px:
            clines.append(cur)
            cur = ch
            w = cw
        else:
            cur += ch
            w += cw
    if cur:
        clines.append(cur)
    return clines


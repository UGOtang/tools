# ========== 初始化I2C和OLED ==========
i2c = I2C(I2C_ID, scl=Pin(SCL_PIN), sda=Pin(SDA_PIN), freq=I2C_FREQ)
addr_list = i2c.scan()
if not addr_list:
    print("错误：未找到I2C设备！请检查接线。")
    sys.exit()
print("I2C设备地址：", [hex(a) for a in addr_list])
# 这里直接使用 SSD1306_I2C，而不是 ssd1306.SSD1306_I2C
oled = SSD1306_I2C(OLED_WIDTH, OLED_HEIGHT, i2c)
# ---- 柔化设置：黑底 + copy版压暗三件套（开机设一次） ----
# 注意：invert(True)=白底是全屏点亮，最刺眼费电，必须用 False
bright_idx = BRIGHT_IDX_DEFAULT

def apply_brightness():
    try:
        oled.contrast(BRIGHT_LEVELS[bright_idx])
    except OSError:
        pass

def apply_dim_base():
    try:
        oled.invert(False)
        oled.write_cmd(SET_PRECHARGE)
        oled.write_cmd(0x11)
        oled.write_cmd(SET_VCOM_DETECT)
        oled.write_cmd(0x00)
    except OSError:
        pass

apply_dim_base()
apply_brightness()
print("cn v6 running, bright=", BRIGHT_LEVELS[bright_idx], "dither=", DITHER)
